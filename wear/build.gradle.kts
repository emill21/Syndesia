// The watch helper. Same applicationId and signing key as the phone app: Wear OS only lets the
// two talk over Bluetooth (the Data Layer) when both match. The phone app embeds this APK.
android {
    namespace = "com.syndesia.wear"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.syndesia.app"
        minSdk = 30
        targetSdk = 35
        versionCode = project.findProperty("syndesiaVersionCode").toString().toInt()
        versionName = project.findProperty("syndesiaVersionName").toString()
    }

    val signing = Properties().apply {
        rootProject.file("keystore/signing.properties").takeIf { it.exists() }?.inputStream()?.use { load(it) }
    }
    signingConfigs {
        create("syndesia") {
            storeFile = rootProject.file(signing.getProperty("storeFile", "keystore/syndesia.jks"))
            storePassword = signing.getProperty("storePassword")
            keyAlias = signing.getProperty("keyAlias")
            keyPassword = signing.getProperty("keyPassword")
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.getByName("syndesia")
        }
        debug {
            signingConfig = signingConfigs.getByName("syndesia")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }
    buildFeatures { compose = true }
    lint {
        abortOnError = false
        checkReleaseBuilds = false
    }
}

